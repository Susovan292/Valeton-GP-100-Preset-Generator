      function getNrPosition(p) {
        const i = p.blocks.findIndex((b) => b[0] === "NR");
        if (i < 0) return "Bypassed";
        if (i === 1 && p.blocks[0][0] === "PRE") return "First / before gain";
        if (i > 0 && p.blocks[i - 1][0] === "DST")
          return "After DST / before AMP";
        if (i > 0 && p.blocks[i - 1][0] === "AMP")
          return "After AMP / before CAB";
        return "Custom position";
      }
      function getNrReason(p) {
        const n = p.blocks.find((b) => b[0] === "NR");
        return n ? n[2] || "Noise reduction" : "No gate";
      }

      function getPreInfo(p) {
        const b = p.blocks.find((x) => x[0] === "PRE");
        if (!b || b[1] === "OFF")
          return {
            model: "OFF",
            settings: "Bypassed",
            reason: "PRE is intentionally bypassed for this tone.",
          };
        const reasons = {
          gilmour:
            "Light compression evens the lead attack without choking the long sustain.",
          slash:
            "A front-end wah adds the expressive vocal quality of the lead; keep it still for the basic tone and sweep it when needed.",
          sultans:
            "Gentle compression evens clean fingerpicked and hybrid-picked transients before the low-gain drive.",
          srv: "Light compression supports the percussive blues attack while retaining picking dynamics.",
          mayer:
            "Moderate compression firms up the clean edge-of-breakup attack and sustain without flattening the response.",
          evh: "PRE is bypassed intentionally so the guitar hits the high-gain amp directly.",
          worship:
            "Subtle compression smooths clean and ambient picking before the drive while leaving delay/reverb tails untouched.",
          dreamy:
            "Light compression evens clean arpeggios and sustained chords before modulation, delay and reverb.",
        };
        return {
          model: b[1],
          settings: b[2] || "See block",
          reason:
            reasons[p.id] || "PRE is used as a front-end tone-shaping stage.",
        };
      }

