      function updateAllNoiseGates() {
        const all = patches;
        for (const p of all) {
          const cat = (p.cat || "").toLowerCase(),
            ampText = (p.blocks.find((b) => b[0] === "AMP") || [])[2] || "",
            ampGain =
              parseInt(
                (String(ampText).match(/Gain\s+(\d+)/) || [])[1] || "0",
                10,
              ) || 0;
          const pickup = (p.pickup || "").toLowerCase();
          const highGain =
            cat.includes("metal") ||
            ampGain >= 70 ||
            /high gain|metal|heavy|tight|chug/i.test(
              (p.song || "") + " " + (p.tags || ""),
            );
          const ambient =
            cat.includes("ambient") ||
            cat.includes("worship") ||
            cat.includes("dreamy");
          const clean =
            cat.includes("clean") ||
            cat.includes("funk") ||
            cat.includes("blues");
          const single =
            pickup.includes("single-coil") || pickup.includes("single coil");
          let pos = "after_amp",
            model = "Gate 1",
            thresh = 15,
            attack = null,
            rel = null;
          if (ambient) {
            pos = "after_amp";
            model = "Gate 1";
            thresh = 3;
          } else if (highGain) {
            pos = "after_dst";
            model = "Gate 2";
            thresh = Math.min(40, Math.max(28, ampGain - 42));
            attack = 8;
            rel = 24;
          } else if (clean && single) {
            pos = "first";
            model = "Gate 1";
            thresh = 5;
          } else if (cat.includes("solos") || cat.includes("leads")) {
            pos = "after_amp";
            model = "Gate 1";
            thresh = ampGain >= 60 ? 18 : 9;
          } else if (
            cat.includes("rock") ||
            cat.includes("80s") ||
            cat.includes("crunch")
          ) {
            pos = "after_amp";
            model = "Gate 1";
            thresh = 20;
          } else {
            pos = "after_amp";
            model = "Gate 1";
            thresh = 10;
          }
          let rows = p.blocks.filter((b) => b[0] !== "NR");
          const nr = [
            "NR",
            model,
            `Thresh ${thresh}${attack !== null ? ` • Attack ${attack} • Rel ${rel}` : ""} • Position: ${pos.replace("_", " ")}`,
          ];
          let idx = 3;
          if (pos === "first") idx = 1;
          if (pos === "after_dst") idx = 2;
          if (idx > rows.length) idx = rows.length;
          rows.splice(idx, 0, nr);
          p.blocks = rows;
          p.params = (p.params || []).filter(
            (x) => !String(x[0]).startsWith("NR "),
          );
          p.params.push(["NR Thresh", String(thresh)]);
          if (attack !== null) {
            p.params.push(["NR Attack", String(attack)]);
            p.params.push(["NR Rel", String(rel)]);
          }
          p.params.push([
            "NR Position",
            pos === "first"
              ? "First (before DST)"
              : pos === "after_dst"
                ? "After DST"
                : "After AMP",
          ]);
          p.nrLogic =
            pos === "first"
              ? "Placed first to reduce guitar/pickup noise before gain."
              : pos === "after_dst"
                ? "Placed after drive to tighten stop/start playing before the high-gain amp."
                : "Placed after the amp to catch amp-generated hiss while keeping the gate before delay/reverb tails.";
        }
      }
